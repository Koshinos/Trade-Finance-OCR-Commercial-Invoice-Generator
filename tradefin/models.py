    base_unit_price_numeric: str = ""
    total_quantity_shipped: str = ""
    adjusted_base_price: str = ""
    total_shipment_value: str = ""
    actual_tm_result: str = ""
    actual_ash_result: str = ""
    actual_inherent_moisture: str = ""
    actual_volatile_matter: str = ""
